// failingSubmitMock 让提交一直失败，从而进入提交重试逻辑
func failingSubmitMock() *recordingMockClient {
	return &recordingMockClient{
		errFor: func(path string) error {
			if strings.HasSuffix(path, "submitJob") {
				return errors.New("submit unavailable")
			}
			return nil
		},
	}
}

// 取消之后继续重试提交，等于把一个已经取消的作业重新交上去。
func TestCancel_StopsSubmitRetries(t *testing.T) {
	mock := failingSubmitMock()
	conn := newTestConnWithRetries(mock, 3)

	cancelSent := false
	mock.onPost = func() {
		if cancelSent {
			return
		}
		cancelSent = true
		if err := conn.Cancel(""); err != nil {
			t.Errorf("Cancel during submit failed: %v", err)
		}
	}

	_, err := conn.execInternal(context.Background(), "select 1\n;", nil)
	if err == nil {
		t.Fatal("expected execInternal to report an error")
	}
	// 失败原因要指向取消，否则调用方分不清是取消还是重试耗尽
	if !strings.Contains(err.Error(), "cancel") {
		t.Errorf("error = %q, want it to report the cancellation", err)
	}

	if n := len(mock.requestsTo("submitJob")); n != 1 {
		t.Errorf("submitJob attempts = %d, want 1 (cancelled after the first attempt)", n)
	}
}

// 取消别的 job 不该影响本连接上正在提交的 job。
func TestCancelJob_OtherJobDoesNotStopSubmitRetries(t *testing.T) {
	mock := failingSubmitMock()
	conn := newTestConnWithRetries(mock, 2)

	cancelSent := false
	mock.onPost = func() {
		if cancelSent {
			return
		}
		cancelSent = true
		if err := conn.CancelJob("some-other-job", ""); err != nil {
			t.Errorf("CancelJob failed: %v", err)
		}
	}

	if _, err := conn.execInternal(context.Background(), "select 1\n;", nil); err == nil {
		t.Fatal("expected execInternal to report an error")
	}

	if n := len(mock.requestsTo("submitJob")); n != 2 {
		t.Errorf("submitJob attempts = %d, want 2 (unrelated cancel must not stop retries)", n)
	}
}

// 取消状态属于单次查询，下一条查询必须能重新提交。
func TestCancel_DoesNotBlockLaterQueries(t *testing.T) {
	mock := failingSubmitMock()
	conn := newTestConnWithRetries(mock, 1)

	cancelSent := false
	mock.onPost = func() {
		if cancelSent {
			return
		}
		cancelSent = true
		if err := conn.Cancel(""); err != nil {
			t.Errorf("Cancel during submit failed: %v", err)
		}
	}

	if _, err := conn.execInternal(context.Background(), "select 1\n;", nil); err == nil {
		t.Fatal("expected the first query to report an error")
	}
	if _, err := conn.execInternal(context.Background(), "select 2\n;", nil); err == nil {
		t.Fatal("expected the second query to report an error")
	}

	if n := len(mock.requestsTo("submitJob")); n != 2 {
		t.Errorf("submitJob attempts = %d, want 2 (the second query must still be submitted)", n)
	}
}

// 取消请求自己失败时不能当成已取消，否则会白白丢掉一次本可成功的提交。
func TestCancel_FailedRequestDoesNotStopSubmitRetries(t *testing.T) {
	mock := &recordingMockClient{
		errFor: func(path string) error {
			if strings.HasSuffix(path, "submitJob") {
				return errors.New("submit unavailable")
			}
			if strings.HasSuffix(path, "cancelJob") {
				return errors.New("cancel unavailable")
			}
			return nil
		},
	}
	conn := newTestConnWithRetries(mock, 2)

	cancelTried := false
	var cancelErr error
	mock.onPost = func() {
		if cancelTried {
			return
		}
		cancelTried = true
		cancelErr = conn.Cancel("")
	}

	if _, err := conn.execInternal(context.Background(), "select 1\n;", nil); err == nil {
		t.Fatal("expected execInternal to report an error")
	}
	if cancelErr == nil {
		t.Fatal("expected Cancel to surface the failed cancel request")
	}
	if n := len(mock.requestsTo("submitJob")); n != 2 {
		t.Errorf("submitJob attempts = %d, want 2 (a failed cancel must not stop retries)", n)
	}
}

