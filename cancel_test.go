// recordingMockClient records the path and payload of every Post so tests can
// assert on the request actually sent to the server.
type recordingMockClient struct {
	mu       sync.Mutex
	requests []recordedRequest
	body     []byte
	onPost   func()
	// errFor 按请求路径决定该次 Post 是否失败
	errFor func(path string) error
}

type recordedRequest struct {
	path string
	body []byte
}

func (m *recordingMockClient) Post(_ context.Context, u *url.URL, _ map[string]string, body []byte, _ time.Duration) (*http.Response, error) {
	m.mu.Lock()
	m.requests = append(m.requests, recordedRequest{path: u.Path, body: append([]byte(nil), body...)})
	m.mu.Unlock()
	if m.onPost != nil {
		m.onPost()
	}
	if m.errFor != nil {
		if err := m.errFor(u.Path); err != nil {
			return nil, err
		}
	}
	respBody := m.body
	if respBody == nil {
		respBody = []byte(`{"status":{"state":"SUCCEED"}}`)
	}
	return &http.Response{
		StatusCode: 200,
		Body:       io.NopCloser(bytes.NewReader(respBody)),
	}, nil
}

func (m *recordingMockClient) Get(_ context.Context, _ *url.URL, _ map[string]string, _ time.Duration) (*http.Response, error) {
	return nil, errors.New("not implemented")
}

func (m *recordingMockClient) Close() error { return nil }

func (m *recordingMockClient) requestsTo(suffix string) []recordedRequest {
	m.mu.Lock()
	defer m.mu.Unlock()
	var out []recordedRequest
	for _, req := range m.requests {
		if strings.HasSuffix(req.path, suffix) {
			out = append(out, req)
		}
	}
	return out
}

func (m *recordingMockClient) requestCount() int {
	m.mu.Lock()
	defer m.mu.Unlock()
	return len(m.requests)
}

func parseRequest(t *testing.T, body []byte) *fastjson.Value {
	t.Helper()
	val, err := fastjson.ParseBytes(body)
	if err != nil {
		t.Fatalf("request body is not valid json: %v", err)
	}
	return val
}

// onlyCancelRequest asserts exactly one cancel was sent and returns its payload.
func onlyCancelRequest(t *testing.T, mock *recordingMockClient) *fastjson.Value {
	t.Helper()
	reqs := mock.requestsTo("cancelJob")
	if len(reqs) != 1 {
		t.Fatalf("expected 1 cancelJob request, got %d", len(reqs))
	}
	return parseRequest(t, reqs[0].body)
}

// A job cancelled by the SDK's own timeout watchdog must be attributable to the
// timeout, not to the caller.
func TestCheckJobTimeout_CancelsWithTimeoutUserAgent(t *testing.T) {
	mock := &recordingMockClient{}
	conn := newTestConn(mock)

	timedOut := conn.checkJobTimeout(1, time.Now().Add(-2*time.Second), jobId{ID: "job-timeout"}, map[string]string{})
	if !timedOut {
		t.Fatal("expected the job to be reported as timed out")
	}

	req := onlyCancelRequest(t, mock)
	if got := string(req.GetStringBytes("user_agent")); got != "gosdk_by_timeout" {
		t.Errorf("user_agent = %q, want %q", got, "gosdk_by_timeout")
	}
	if got := string(req.GetStringBytes("job_id", "id")); got != "job-timeout" {
		t.Errorf("job_id.id = %q, want %q", got, "job-timeout")
	}
}

