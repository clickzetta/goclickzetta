// Cancel targets whatever job the connection is running, so it must pick up the
// job id generated by execInternal rather than require the caller to know it.
func TestCancel_CancelsJobRunningOnConnection(t *testing.T) {
	mock := &recordingMockClient{}
	conn := newTestConnWithRetries(mock, 1)

	var cancelErr error
	cancelSent := false
	mock.onPost = func() {
		if cancelSent {
			return
		}
		cancelSent = true
		cancelErr = conn.Cancel("")
	}

	if _, err := conn.execInternal(context.Background(), "select 1\n;", nil); err != nil {
		t.Fatalf("unexpected exec error: %v", err)
	}
	if cancelErr != nil {
		t.Fatalf("Cancel during exec failed: %v", cancelErr)
	}

	submitted := mock.requestsTo("submitJob")
	if len(submitted) != 1 {
		t.Fatalf("expected 1 submitJob request, got %d", len(submitted))
	}
	runningJobID := string(parseRequest(t, submitted[0].body).GetStringBytes("jobDesc", "jobId", "id"))
	if runningJobID == "" {
		t.Fatal("could not read the job id out of the submitJob request")
	}

	req := onlyCancelRequest(t, mock)
	if got := string(req.GetStringBytes("job_id", "id")); got != runningJobID {
		t.Errorf("cancelled job_id.id = %q, want the running job %q", got, runningJobID)
	}
	if got := string(req.GetStringBytes("user_agent")); got != "gosdk_by_user" {
		t.Errorf("user_agent = %q, want %q", got, "gosdk_by_user")
	}
}

